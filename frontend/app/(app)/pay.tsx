/**
 * pay.tsx — v27k (2026-02-14) full redesign of the activation page.
 *
 * Flow: Country → auto-determined method (Mobile Money operator list OR
 * USDT BEP20 fallback) → phone (mobile only) → "ACTIVER MON COMPTE".
 *
 * All countries from `/api/payments/activation-catalog` are shown, even
 * those with no Mobile Money operator (they get USDT BEP20 automatically).
 * The frontend never sees the underlying gateway names — the server
 * decides via `/api/payments/activate`.
 */
import React, { useEffect, useMemo, useState } from "react";
import {
  ActivityIndicator, Image, Modal, SafeAreaView, ScrollView,
  StyleSheet, Text, TextInput, TouchableOpacity, View,
} from "react-native";
import { Ionicons } from "@expo/vector-icons";
import { useRouter } from "expo-router";
import { api } from "@/src/api";
import { useAuth } from "@/src/auth";
import { theme } from "@/src/theme";
import ActivationVideoList from "@/src/components/ActivationVideoList";

type Operator = {
  code: string;
  label: string;
  currency: string;
  gateway: string;
  // v27bb (2026-03-05) — operators that need an OTP generated by the user
  // (ex. Orange Money Burkina → `*144*4*6*{amount}#`) are annotated so
  // the frontend can show the USSD code + OTP input PROACTIVELY, before
  // the first submission.
  requires_otp?: boolean;
  otp_ussd_template?: string;
};
type CountryEntry = {
  code: string;
  name: string;
  flag?: string;
  dial?: string;
  type: "mobile" | "crypto";
  operators: Operator[];
  currency?: string;
  crypto_available?: boolean;
};
type Catalog = {
  amount_fcfa: number;
  crypto_available: boolean;
  countries: CountryEntry[];
};

export default function Pay() {
  const router = useRouter();
  const { refresh } = useAuth();
  const [catalog, setCatalog] = useState<Catalog | null>(null);
  const [catalogErr, setCatalogErr] = useState<string | null>(null);

  const [countryCode, setCountryCode] = useState<string>("");
  const [operatorCode, setOperatorCode] = useState<string>("");
  const [phone, setPhone] = useState<string>("");

  const [loading, setLoading] = useState(false);
  const [err, setErr] = useState<string | null>(null);
  const [ref, setRef] = useState<string | null>(null);
  const [phase, setPhase] = useState<"idle" | "pending" | "success" | "failed">("idle");
  const [cryptoAddr, setCryptoAddr] = useState<{
    address?: string; qr?: string; amount?: number; asset?: string; network?: string;
  } | null>(null);
  const [countryPicker, setCountryPicker] = useState(false);
  const [operatorPicker, setOperatorPicker] = useState(false);
  // v27az (2026-03-05) — Orange BF (et autres opérateurs à OTP) renvoient
  // HTTP 400 { code: "OTP_REQUIRED", ussd, message, payment_flow } tant
  // que l'OTP n'est pas fourni. On capture ce payload pour afficher :
  //   • Le code USSD exact à composer (ex. *144*4*6*2650#) — copiable
  //   • Un champ pour saisir l'OTP reçu
  //   • Un bouton « Valider le paiement » qui re-soumet avec l'OTP.
  const [otpFlow, setOtpFlow] = useState<null | {
    ussd: string; message: string; label?: string; steps?: string[];
    actionLabel?: string;
  }>(null);
  const [otp, setOtp] = useState<string>("");
  const [copied, setCopied] = useState<boolean>(false);
  // v27i (2026-02-20) — Restore the "Hash de transaction" field on the
  // crypto pending screen. After sending USDT the user pastes the on-chain
  // hash and hits "Valider le paiement". Backend
  // `POST /api/activations/crypto-auto/verify` verifies the hash against
  // IziChangePay (uniqueness, amount, status, hash match).
  const [txHash, setTxHash] = useState<string>("");
  const [hashSubmitting, setHashSubmitting] = useState(false);
  const [hashErr, setHashErr] = useState<string | null>(null);

  useEffect(() => {
    (async () => {
      try {
        const c = await api.get<Catalog>("/payments/activation-catalog");
        setCatalog(c);
      } catch (e: any) {
        setCatalogErr(e?.detail || "Impossible de charger la liste des pays.");
      }
    })();
  }, []);

  const selectedCountry = useMemo(
    () => catalog?.countries.find((c) => c.code === countryCode) || null,
    [catalog, countryCode],
  );
  const operators = selectedCountry?.operators || [];
  const selectedOperator = useMemo(
    () => operators.find((o) => o.code === operatorCode) || null,
    [operators, operatorCode],
  );
  // v27l (2026-02-14) — the "mode" is derived from the selected operator's
  // gateway, not from the country. Any country can offer USDT BEP20
  // alongside its Mobile Money operators; the phone field only shows when
  // the picked operator is NOT the crypto one.
  // v27w (2026-02-24) — two crypto gateways: izichange (legacy) & biztranspay_crypto (new).
  const isIziCrypto = selectedOperator?.gateway === "izichange";
  const isBtpCrypto = selectedOperator?.gateway === "biztranspay_crypto";
  const isCryptoPick = isIziCrypto || isBtpCrypto;
  const isMobilePick = !!selectedOperator && !isCryptoPick;
  // v27bb — proactively compute the USSD code + requires_otp flag from
  // the selected operator so we can render the OTP card BEFORE the user
  // hits "ACTIVER MON COMPTE". The amount placeholder `{amount}` is
  // substituted with the real activation amount (2 650).
  const amountInt = catalog?.amount_fcfa ?? 2650;
  const operatorRequiresOtp = !!selectedOperator?.requires_otp;
  const operatorUssd = useMemo(() => {
    const tpl = selectedOperator?.otp_ussd_template || "";
    if (!tpl) return "";
    return tpl.replace("{amount}", String(amountInt));
  }, [selectedOperator, amountInt]);

  // The frontend routes verify calls to the correct endpoint based on which
  // crypto gateway created the deposit.
  const [currentGateway, setCurrentGateway] = useState<string>("");
  // Country picker helper — show "mixte" when a country has both a mobile
  // operator AND USDT_BEP20.
  const countryHasMobile = (c: CountryEntry) =>
    c.operators.some((o) => o.gateway !== "izichange" && o.gateway !== "biztranspay_crypto");

  // When the country changes, always clear operator + phone. Auto-select
  // USDT_BEP20 only when it is the ONLY option available (pays sans MoMo).
  const pickCountry = (cc: string) => {
    setCountryCode(cc);
    setCountryPicker(false);
    const c = catalog?.countries.find((x) => x.code === cc) || null;
    setPhone("");
    if (c && c.operators.length === 1) {
      setOperatorCode(c.operators[0].code);
    } else {
      setOperatorCode("");
    }
  };

  const canActivate = useMemo(() => {
    if (!selectedCountry || !selectedOperator) return false;
    if (isCryptoPick) return true;
    if (phone.replace(/\s/g, "").length < 6) return false;
    // v27bb — require the OTP input to be filled when the operator
    // explicitly demands it (Orange BF). The CTA stays disabled until
    // the user has composed the USSD on their phone AND typed the OTP.
    if (operatorRequiresOtp && otp.trim().length < 4) return false;
    return true;
  }, [selectedCountry, selectedOperator, isCryptoPick, phone, operatorRequiresOtp, otp]);

  const activate = async () => {
    if (!selectedCountry || !selectedOperator) return;
    setErr(null);
    setLoading(true);
    try {
      const body: any = { method: isCryptoPick ? "crypto" : "mobile" };
      if (isCryptoPick) {
        // v27w — tell the backend which crypto gateway to hit.
        body.provider = isBtpCrypto ? "biztranspay" : "izichange";
      }
      if (!isCryptoPick) {
        body.country = selectedCountry.code;
        body.operator = operatorCode;
        body.phone = phone;
        // v27az — forward the OTP (if the user typed one). Backend ignores
        // for operators that don't need it (e.g. T-Money, Moov).
        if (otp.trim()) body.otp = otp.trim();
      }
      const r = await api.post<any>("/payments/activate", body);
      setRef(r.reference);
      setCurrentGateway(String(r.gateway || (isBtpCrypto ? "biztranspay" : "izichange")));
      if (r.method === "crypto") {
        setCryptoAddr({
          address: r.deposit_address, qr: r.qr_data,
          amount: r.amount, asset: r.asset_code, network: r.network,
        });
      }
      // v27az — on success clear any leftover OTP flow state.
      setOtpFlow(null);
      setOtp("");
      setPhase("pending");
    } catch (e: any) {
      // v27az — detect OTP_REQUIRED backend contract and render a proper
      // UI instead of dumping the raw JSON object as the error message.
      const detail = e?.detail;
      const isOtp =
        detail && typeof detail === "object" && detail.code === "OTP_REQUIRED";
      if (isOtp) {
        const flow = (detail && detail.payment_flow) || {};
        setOtpFlow({
          ussd: String(detail.ussd || flow.ussd_code || ""),
          message: String(detail.message || "Composez le code USSD puis saisissez l'OTP."),
          label: flow.otp_label || "Code OTP",
          steps: Array.isArray(flow.steps) ? flow.steps : undefined,
          actionLabel: flow.action_label || "J'ai mon code, lancer le paiement",
        });
        setErr(null);
      } else {
        // Fall back to the usual string message (never render raw JSON).
        let msg =
          (detail && typeof detail === "object" ? detail.message : detail) ||
          e?.message ||
          "Erreur lors du lancement du paiement.";
        if (typeof msg !== "string") {
          try { msg = JSON.stringify(msg); } catch { msg = "Erreur inconnue."; }
        }
        setErr(msg);
      }
    } finally {
      setLoading(false);
    }
  };

  // Poll pending payment → dashboard on success.
  useEffect(() => {
    if (phase !== "pending" || !ref) return;
    let missed = 0;
    const t = setInterval(async () => {
      try {
        const r = await api.get<any>(`/payments/${ref}/status`);
        missed = 0;
        const s = String(r.status || "").toLowerCase();
        if (["paid", "success", "validated", "completed"].includes(s) || r.activation_done === true) {
          setPhase("success"); try { await refresh?.(); } catch {}
          setTimeout(() => {
            if (typeof window !== "undefined") window.location.href = "/dashboard";
            else router.replace("/(app)/dashboard" as any);
          }, 1200);
        } else if (["failed", "rejected", "cancelled", "canceled", "expired"].includes(s)) {
          setPhase("failed");
        }
      } catch {
        missed += 1;
        if (missed >= 6) setErr("Impossible de vérifier le paiement. Actualisez la page.");
      }
    }, 3000);
    return () => clearInterval(t);
  }, [phase, ref, refresh, router]);

  const copy = (v: string) => {
    if (typeof navigator !== "undefined" && navigator.clipboard) {
      navigator.clipboard.writeText(v);
    }
  };

  // ─── RENDER ─────────────────────────────────────────────────────────
  return (
    <SafeAreaView style={styles.root}>
      <View style={styles.header}>
        <TouchableOpacity onPress={() => router.back()} style={styles.iconBtn} testID="pay-back">
          <Ionicons name="chevron-back" size={22} color={theme.colors.textPrimary} />
        </TouchableOpacity>
        <Text style={styles.title}>Activer mon compte</Text>
        <View style={{ width: 40 }} />
      </View>

      <ScrollView contentContainerStyle={{ padding: 16, paddingBottom: 140 }}>
        {/* Header amount card */}
        <View style={styles.amountCard}>
          <Text style={styles.amountLabel}>ACTIVATION DU COMPTE</Text>
          <Text style={styles.amountValue} testID="pay-amount">
            {(catalog?.amount_fcfa ?? 2650).toLocaleString("fr-FR").replace(/,/g, "\u202f")} FCFA
          </Text>
          <Text style={styles.amountSub}>Montant fixe · non modifiable</Text>
        </View>

        {catalogErr && <Text style={styles.err}>❌ {catalogErr}</Text>}
        {!catalog && !catalogErr && (
          <View style={{ padding: 24, alignItems: "center" }}>
            <ActivityIndicator color={theme.colors.primary} />
          </View>
        )}

        {catalog && phase === "idle" && (
          <>
            {/* Step 1 — country */}
            <Text style={styles.label}>🌍 Choisissez votre pays</Text>
            <TouchableOpacity
              style={styles.selector}
              onPress={() => setCountryPicker(true)}
              testID="pay-country-selector"
            >
              {selectedCountry ? (
                <Text style={styles.selectorTxt}>
                  {selectedCountry.flag} {selectedCountry.name}
                </Text>
              ) : (
                <Text style={styles.selectorPh}>Sélectionner un pays</Text>
              )}
              <Ionicons name="chevron-down" size={18} color={theme.colors.textSecondary} />
            </TouchableOpacity>

            {/* Step 2 — operator (mobile ops + USDT always as an extra choice) */}
            {selectedCountry && (
              <>
                <Text style={styles.label}>
                  💳 Choisissez votre moyen de paiement
                </Text>
                {selectedCountry.operators.length === 1 ? (
                  <View style={[styles.selector, styles.selectorLocked]} testID="pay-usdt-fixed">
                    <View style={{ flexDirection: "row", alignItems: "center", gap: 8 }}>
                      <Ionicons
                        name={selectedCountry.operators[0].gateway === "izichange" ? "logo-bitcoin" : "phone-portrait"}
                        size={18}
                        color={theme.colors.primary}
                      />
                      <Text style={styles.selectorTxt}>{selectedCountry.operators[0].label}</Text>
                    </View>
                    <Ionicons name="lock-closed" size={14} color={theme.colors.textSecondary} />
                  </View>
                ) : (
                  <TouchableOpacity
                    style={styles.selector}
                    onPress={() => setOperatorPicker(true)}
                    testID="pay-operator-selector"
                  >
                    {selectedOperator ? (
                      <View style={{ flexDirection: "row", alignItems: "center", gap: 8 }}>
                        <Ionicons
                          name={isCryptoPick ? "logo-bitcoin" : "phone-portrait"}
                          size={18}
                          color={theme.colors.primary}
                        />
                        <Text style={styles.selectorTxt}>{selectedOperator.label}</Text>
                      </View>
                    ) : (
                      <Text style={styles.selectorPh}>Sélectionner un moyen de paiement</Text>
                    )}
                    <Ionicons name="chevron-down" size={18} color={theme.colors.textSecondary} />
                  </TouchableOpacity>
                )}
              </>
            )}

            {/* Step 3 — phone (mobile ops only) */}
            {selectedCountry && isMobilePick && (
              <>
                <Text style={styles.label}>📞 Numéro de téléphone</Text>
                <TextInput
                  style={styles.input}
                  value={phone}
                  onChangeText={setPhone}
                  placeholder="Entrez le numéro qui sera débité"
                  placeholderTextColor={theme.colors.textSecondary}
                  keyboardType="phone-pad"
                  testID="pay-phone"
                />
              </>
            )}

            {/* v27bb — PROACTIVE OTP card (Orange BF & any operator with
                requires_otp=true). Rendered as soon as the operator is
                selected, BEFORE the user clicks "ACTIVER MON COMPTE". The
                user:
                  1. Reads/copies the USSD code (ex. *144*4*6*2650#)
                  2. Dials it on their phone, gets the OTP code
                  3. Types the OTP in the field below
                  4. Clicks "ACTIVER MON COMPTE" (now enabled)
                The activation request includes `otp` from the start, so
                Biz-transPay accepts it on the first try (no 400 bounce). */}
            {selectedCountry && isMobilePick && (operatorRequiresOtp || otpFlow) && (
              <View style={styles.otpCard} testID="pay-otp-flow">
                <View style={styles.otpHeader}>
                  <Ionicons name="shield-checkmark" size={22} color="#F59E0B" />
                  <Text style={styles.otpTitle}>Code de confirmation requis</Text>
                </View>
                <Text style={styles.otpSubtitle}>
                  Pour Orange Money Burkina, générez votre code OTP avant de valider.
                </Text>

                {/* Step 1 — USSD code (big, bold, copyable). */}
                <Text style={styles.otpStep}>
                  1️⃣ Composez ce code sur votre téléphone :
                </Text>
                <View style={styles.ussdBox}>
                  <Text selectable style={styles.ussdCode} testID="pay-otp-ussd">
                    {operatorUssd || otpFlow?.ussd || "—"}
                  </Text>
                  <TouchableOpacity
                    onPress={() => {
                      const code = operatorUssd || otpFlow?.ussd || "";
                      if (!code) return;
                      copy(code);
                      setCopied(true);
                      setTimeout(() => setCopied(false), 1500);
                    }}
                    style={styles.ussdCopyBtn}
                    testID="pay-otp-copy"
                  >
                    <Ionicons name={copied ? "checkmark" : "copy"} size={14} color="#fff" />
                    <Text style={styles.copyTxt}>{copied ? "Copié" : "Copier"}</Text>
                  </TouchableOpacity>
                </View>

                <Text style={styles.otpStepLine}>
                  2️⃣ Suivez le menu Orange Money pour générer votre code OTP.
                </Text>
                <Text style={styles.otpStepLine}>
                  3️⃣ Copiez le code reçu dans le champ ci-dessous.
                </Text>

                {/* Step 4 — OTP input */}
                <Text style={[styles.otpStep, { marginTop: 14 }]}>
                  🔐 4️⃣ Saisissez votre code OTP :
                </Text>
                <TextInput
                  style={styles.otpInput}
                  value={otp}
                  onChangeText={setOtp}
                  placeholder="Ex: 123456"
                  placeholderTextColor={theme.colors.textSecondary}
                  keyboardType="number-pad"
                  maxLength={10}
                  testID="pay-otp-input"
                />
                <Text style={styles.otpFooter}>
                  5️⃣ Tapez ensuite « ACTIVER MON COMPTE » ci-dessous.
                </Text>
              </View>
            )}

            {err && <Text style={styles.err}>❌ {err}</Text>}

            <TouchableOpacity
              style={[styles.cta, !canActivate && styles.ctaDisabled]}
              disabled={!canActivate || loading}
              onPress={activate}
              testID="pay-activate"
            >
              {loading ? (
                <ActivityIndicator color="#fff" />
              ) : (
                <>
                  <Text style={styles.ctaTxt}>ACTIVER MON COMPTE</Text>
                  <Ionicons name="arrow-forward" size={18} color="#fff" />
                </>
              )}
            </TouchableOpacity>
          </>
        )}

        {/* Pending state */}
        {phase === "pending" && (
          <View style={styles.pendingCard}>
            <ActivityIndicator color={theme.colors.primary} size="large" />
            <Text style={styles.pendingTitle}>Paiement en cours…</Text>
            {cryptoAddr?.address ? (
              <>
                <Text style={styles.pendingSub}>
                  Envoyez {cryptoAddr.amount} {cryptoAddr.asset} sur le réseau {cryptoAddr.network} à l'adresse :
                </Text>
                <View style={styles.addrBox}>
                  <Text selectable style={styles.addrTxt}>{cryptoAddr.address}</Text>
                </View>
                <TouchableOpacity
                  style={styles.copyBtn}
                  onPress={() => copy(cryptoAddr.address!)}
                  testID="pay-copy-addr"
                >
                  <Ionicons name="copy" size={14} color="#fff" />
                  <Text style={styles.copyTxt}>Copier l'adresse</Text>
                </TouchableOpacity>
                {cryptoAddr.qr ? (
                  <Image
                    source={{ uri: `https://api.qrserver.com/v1/create-qr-code/?size=180x180&data=${encodeURIComponent(cryptoAddr.qr)}` }}
                    style={{ width: 180, height: 180, marginTop: 12 }}
                  />
                ) : null}
                <Text style={styles.pendingHint}>
                  Le compte sera activé automatiquement dès réception du paiement.
                </Text>

                {/* v27i — Manuel : coller la hash on-chain pour accélérer la validation */}
                <View style={{ marginTop: 18, width: "100%" }}>
                  <Text style={[styles.label, { textAlign: "center", marginTop: 0 }]}>
                    🔗 Ou collez la hash de votre transaction
                  </Text>
                  <TextInput
                    style={styles.input}
                    value={txHash}
                    onChangeText={(v) => { setTxHash(v); setHashErr(null); }}
                    placeholder="0x…"
                    placeholderTextColor={theme.colors.textSecondary}
                    autoCapitalize="none"
                    testID="pay-tx-hash"
                  />
                  {hashErr && <Text style={styles.err}>❌ {hashErr}</Text>}
                  <TouchableOpacity
                    style={[styles.cta, (!txHash.trim() || hashSubmitting) && styles.ctaDisabled, { marginTop: 6 }]}
                    disabled={!txHash.trim() || hashSubmitting}
                    onPress={async () => {
                      if (!ref) return;
                      setHashSubmitting(true); setHashErr(null);
                      try {
                        // v27w — route to the correct verify endpoint based on
                        // which crypto gateway created the deposit.
                        const verifyPath = currentGateway === "biztranspay"
                          ? "/activations/biztranspay-crypto/verify"
                          : "/activations/crypto-auto/verify";
                        await api.post<any>(verifyPath, {
                          reference: ref, tx_hash: txHash.trim(),
                        });
                        setPhase("success");
                        try { await refresh?.(); } catch {}
                        setTimeout(() => {
                          if (typeof window !== "undefined") window.location.href = "/dashboard";
                          else router.replace("/(app)/dashboard" as any);
                        }, 1200);
                      } catch (e: any) {
                        setHashErr(e?.detail || e?.message || "Hash invalide ou déjà utilisée.");
                      } finally { setHashSubmitting(false); }
                    }}
                    testID="pay-tx-hash-submit"
                  >
                    {hashSubmitting ? (
                      <ActivityIndicator color="#fff" />
                    ) : (
                      <>
                        <Ionicons name="checkmark-done" size={18} color="#fff" />
                        <Text style={styles.ctaTxt}>VALIDER LE PAIEMENT</Text>
                      </>
                    )}
                  </TouchableOpacity>
                  <Text style={{ color: theme.colors.textSecondary, fontSize: 11, textAlign: "center", marginTop: 6, fontStyle: "italic" }}>
                    La hash est vérifiée côté serveur (montant, adresse, réseau, unicité).
                  </Text>
                </View>
              </>
            ) : (
              <Text style={styles.pendingSub}>
                Validez la demande sur votre téléphone. L'activation se fait automatiquement.
              </Text>
            )}
          </View>
        )}

        {phase === "success" && (
          <View style={styles.pendingCard}>
            <Ionicons name="checkmark-circle" size={48} color={theme.colors.success} />
            <Text style={styles.pendingTitle}>✅ Compte activé !</Text>
            <Text style={styles.pendingSub}>Redirection vers le Dashboard…</Text>
          </View>
        )}

        {phase === "failed" && (
          <View style={styles.pendingCard}>
            <Ionicons name="close-circle" size={48} color={theme.colors.danger} />
            <Text style={styles.pendingTitle}>Paiement échoué</Text>
            <TouchableOpacity
              onPress={() => { setPhase("idle"); setRef(null); setErr(null); }}
              style={[styles.cta, { marginTop: 12 }]}
              testID="pay-retry"
            >
              <Text style={styles.ctaTxt}>RÉESSAYER</Text>
            </TouchableOpacity>
          </View>
        )}

        {/* Activation guide videos — configured from admin panel */}
        <ActivationVideoList />
      </ScrollView>

      {/* Country picker modal */}
      <Modal visible={countryPicker} animationType="slide" onRequestClose={() => setCountryPicker(false)}>
        <SafeAreaView style={styles.modalRoot}>
          <View style={styles.modalHeader}>
            <TouchableOpacity onPress={() => setCountryPicker(false)}>
              <Ionicons name="close" size={26} color={theme.colors.textPrimary} />
            </TouchableOpacity>
            <Text style={styles.modalTitle}>Choisissez votre pays</Text>
            <View style={{ width: 26 }} />
          </View>
          <ScrollView>
            {(catalog?.countries || []).map((c) => (
              <TouchableOpacity
                key={c.code}
                style={styles.modalRow}
                onPress={() => pickCountry(c.code)}
                testID={`pay-country-${c.code}`}
              >
                <Text style={styles.modalRowFlag}>{c.flag || "🏳️"}</Text>
                <View style={{ flex: 1 }}>
                  <Text style={styles.modalRowT}>{c.name}</Text>
                  <Text style={styles.modalRowSub}>
                    {countryHasMobile(c)
                      ? `${c.operators.filter((o) => o.gateway !== "izichange").length} Mobile Money + USDT BEP20`
                      : "USDT BEP20"}
                  </Text>
                </View>
                {countryCode === c.code && (
                  <Ionicons name="checkmark-circle" size={20} color={theme.colors.primary} />
                )}
              </TouchableOpacity>
            ))}
          </ScrollView>
        </SafeAreaView>
      </Modal>

      {/* Operator picker modal */}
      <Modal visible={operatorPicker} animationType="slide" onRequestClose={() => setOperatorPicker(false)}>
        <SafeAreaView style={styles.modalRoot}>
          <View style={styles.modalHeader}>
            <TouchableOpacity onPress={() => setOperatorPicker(false)}>
              <Ionicons name="close" size={26} color={theme.colors.textPrimary} />
            </TouchableOpacity>
            <Text style={styles.modalTitle}>Choisissez votre opérateur</Text>
            <View style={{ width: 26 }} />
          </View>
          <ScrollView>
            {(operators || []).map((op) => (
              <TouchableOpacity
                key={op.code}
                style={styles.modalRow}
                onPress={() => { setOperatorCode(op.code); setOperatorPicker(false); }}
                testID={`pay-operator-${op.code}`}
              >
                <Ionicons name="phone-portrait" size={22} color={theme.colors.primary} />
                <View style={{ flex: 1, marginLeft: 12 }}>
                  <Text style={styles.modalRowT}>{op.label}</Text>
                </View>
                {operatorCode === op.code && (
                  <Ionicons name="checkmark-circle" size={20} color={theme.colors.primary} />
                )}
              </TouchableOpacity>
            ))}
          </ScrollView>
        </SafeAreaView>
      </Modal>
    </SafeAreaView>
  );
}

